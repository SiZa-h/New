package com.sizah.content.block;

import com.sizah.common.NewMod;

import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.SoundType;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.material.MapColor;

public final class ModBlocks {
	public static final ResourceKey<Block> BLACK_BLOCK_KEY = ResourceKey.create(
			Registries.BLOCK,
			NewMod.id("black_block")
	);

	public static final ResourceKey<Block> WHITE_BLOCK_KEY = ResourceKey.create(
			Registries.BLOCK,
			NewMod.id("white_block")
	);

	/**
	 * Black block: a placeable full block.
	 * Hardness 1.5, blast resistance 6.0, same sound as stone; it does not require the correct tool,
	 * so breaking it bare-handed still drops itself
	 * (the drop is generated by {@code ModBlockLootProvider}).
	 */
	public static final Block BLACK_BLOCK = new Block(
			BlockBehaviour.Properties.of()
					.setId(BLACK_BLOCK_KEY)
					.mapColor(MapColor.COLOR_BLACK)
					.strength(100.0F, 1200.0F)
					.sound(SoundType.STONE)
	);

	/**
	 * White block: the exact opposite of the black block.
	 *
	 * <p>Every property is mirrored: the same hardness and blast resistance, the same stone sound, the same
	 * "no tool required, drops itself" behaviour, and the map colour on the other end of the scale
	 * ({@link MapColor#SNOW} against {@link MapColor#COLOR_BLACK}). The texture is the black block's picture with
	 * every colour channel inverted — interior {@code #E3E3DF}, border {@code #EDEDEB} against {@code #1C1C20} and
	 * {@code #121214}; both are written by {@code tools/gen-block-textures.js}.
	 */
	public static final Block WHITE_BLOCK = new Block(
			BlockBehaviour.Properties.of()
					.setId(WHITE_BLOCK_KEY)
					.mapColor(MapColor.SNOW)
					.strength(100.0F, 1200.0F)
					.sound(SoundType.STONE)
	);

	private ModBlocks() {
	}

	public static void register() {
		Registry.register(BuiltInRegistries.BLOCK, BLACK_BLOCK_KEY, BLACK_BLOCK);
		Registry.register(BuiltInRegistries.BLOCK, WHITE_BLOCK_KEY, WHITE_BLOCK);
	}
}
